algo = input('Digite algo: ')
print ('Seu tipo primitivo: \033[31m{}\033[m'.format(type(algo)))
print ('É número? \033[31m{}\033[m'.format(algo.isnumeric()))
print ('É alfabético? \033[31m{}\033[m'.format(algo.isalpha()))
print ('É alfanumérico? \033[31m{}\033[m'.format(algo.isalnum()))
print ('Apenas contem espaços? \033[31m{}\033[m'.format(algo.isspace()))
print ('Sua primeira letra está em caixa alta? \033[31m{}\033[m'.format(algo.istitle()))
print ('Está totalmente em caixa alta? \033[31m{}\033[m'.format(algo.isupper()))
print ('Está totalmente em letras minúsculas? \033[31m{}\033[m'.format(algo.islower()))