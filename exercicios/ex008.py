m = float(input('Digite um valor em metros: '))
km = m / 1000
hm = m / 100
dam = m / 10
dm = m * 10
cm = m * 100
mm = m * 1000
print('\nValor em Kilômetros: {}km \nValor em Hectômetros: {}hm'.format(km, hm))
print('Valor em Decâmetros: {}dam \nValor em Decímetros: {}dam'.format(dam, dm))
print ('Valor em Centímetros: {}cm \nValor em Milímetros: {}mm'.format(cm, mm))